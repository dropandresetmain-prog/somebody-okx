const NEGATION_CUE =
  /(?:\b(?:not|no|nor|never|without|cannot|can'?t|avoid\w*|exclude\w*|disclaim\w*|refrain\w*|lack\w*)\b|free of)/;

export function affirmativelyClaimsOutOfScopePhrase(
  loweredPurpose: string,
): string | null {
  for (const phrase of OUT_OF_SCOPE_CLAIM_PHRASES) {
    let searchFrom = 0;
    for (;;) {
      const at = loweredPurpose.indexOf(phrase, searchFrom);
      if (at === -1) break;
      searchFrom = at + phrase.length;
      let clauseStart = 0;
      for (const separator of [".", ";", "!", "?", "\n", ",", "—"]) {
        const idx = loweredPurpose.lastIndexOf(separator, at - 1);
        if (idx + 1 > clauseStart) clauseStart = idx + 1;
      }
      const clause = loweredPurpose.slice(clauseStart, at);
      if (NEGATION_CUE.test(clause)) continue;
      return phrase;
    }
  }
  return null;
}

export function resolveSupportedPurposeKind(
  request: SocialMediaGuruMerchantProductRequest,
):
  | { ok: true; purposeKind: SocialMediaGuruSupportedPurposeKind; purpose: string }
  | { ok: false; error: SocialMediaGuruProtectedErrorCode; detail: string } {
  const purpose = normalizeSocialMediaGuruPurpose(request.purpose);
  if (!purpose) {
    return {
      ok: false,
      error: "incomplete_product_request",
      detail:
        "social_media_guru requires a bounded purpose describing the social-intelligence research question",
    };
  }
  const explicitKind = request.purposeKind?.trim() ?? "";
  if (explicitKind && explicitKind !== SOCIAL_MEDIA_GURU_SUPPORTED_PURPOSE_KIND) {
    return {
      ok: false,
      error: "unsupported_product_scope",
      detail: `purposeKind ${explicitKind.slice(0, 120)} is outside external_social_intelligence scope`,
    };
  }
  const claim = affirmativelyClaimsOutOfScopePhrase(purpose.toLowerCase());
  if (claim) {
    return {
      ok: false,
      error: "unsupported_product_scope",
      detail: `requested purpose requires ${claim}, which social_media_guru does not sell`,
    };
  }
  if (!explicitKind) {
    return {
      ok: false,
      error: "incomplete_product_request",
      detail:
        "social_media_guru requires a structured purposeKind; free-text purpose is descriptive context, not scope authority",
    };
  }
  return {
    ok: true,
    purposeKind: SOCIAL_MEDIA_GURU_SUPPORTED_PURPOSE_KIND,
    purpose,
  };
}

