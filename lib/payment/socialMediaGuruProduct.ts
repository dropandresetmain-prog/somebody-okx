export function socialMediaGuruAuthorizedRequestFromIntent(
  intent: ExecutionIntent,
):
  | { ok: true; request: SocialMediaGuruAuthorizedRequest }
  | { ok: false; reason: string } {
  const problems: string[] = [];
  const text = (value: unknown): string =>
    typeof value === "string" ? value.trim() : "";
  if (intent.kind !== "external_acquisition") {
    problems.push(`intent kind ${String(intent.kind)} is not an external acquisition`);
  }
  const requestId = text(intent.intentId);
  if (!requestId) problems.push("intent has no identity");
  const target: Partial<ExecutionIntent["target"]> = intent.target ?? {};
  const providerId = text(target.providerId);
  const serviceId = text(target.serviceId);
  const offeringId = text(target.offeringId);
  const resourceClass = text(target.resourceClass);
  if (!providerId) problems.push("authorized target has no providerId");
  else if (providerId !== SOCIAL_MEDIA_GURU_PROVIDER_ID) {
    problems.push(
      `authorized provider ${providerId} is not ${SOCIAL_MEDIA_GURU_PROVIDER_ID}`,
    );
  }
  if (!serviceId) problems.push("authorized target has no serviceId");
  else if (serviceId !== SOCIAL_MEDIA_GURU_FULFILLMENT_SCOPE.serviceId) {
    problems.push(
      `authorized service ${serviceId} is not ${SOCIAL_MEDIA_GURU_FULFILLMENT_SCOPE.serviceId}`,
    );
  }
  if (!offeringId) problems.push("authorized target has no offeringId");
  else if (offeringId !== SOCIAL_MEDIA_GURU_OFFERING_ID) {
    problems.push(
      `authorized offering ${offeringId} is not ${SOCIAL_MEDIA_GURU_OFFERING_ID}`,
    );
  }
  if (!resourceClass) problems.push("authorized target has no resourceClass");
  else if (
    !(SOCIAL_MEDIA_GURU_FULFILLMENT_SCOPE.resourceClasses as readonly string[]).includes(
      resourceClass,
    )
  ) {
    problems.push(
      `authorized resource class ${resourceClass} is not declared by the adapter`,
    );
  }
  const purposeKind = text(intent.requestedPurposeKind);
  if (!purposeKind) {
    problems.push(
      "intent carries no application-validated requested scope (requestedPurposeKind)",
    );
  } else if (
    !(SOCIAL_MEDIA_GURU_FULFILLMENT_SCOPE.purposeKinds as readonly string[]).includes(
      purposeKind,
    )
  ) {
    problems.push(
      `requested scope ${purposeKind.slice(0, 120)} is not declared by the adapter`,
    );
  }
  const purpose = normalizeSocialMediaGuruPurpose(intent.purpose);
  if (!purpose) problems.push("intent carries no bounded purpose");
  else {
    const claim = affirmativelyClaimsOutOfScopePhrase(purpose.toLowerCase());
    if (claim) problems.push(`requested purpose affirmatively requires ${claim}`);
  }
  if (problems.length > 0) return { ok: false, reason: problems.join("; ") };
  return {
    ok: true,
    request: {
      requestId,
      providerId,
      serviceId,
      offeringId,
      resourceClass,
      purposeKind: SOCIAL_MEDIA_GURU_SUPPORTED_PURPOSE_KIND,
      purpose,
    },
  };
}

