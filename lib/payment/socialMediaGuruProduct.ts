const PROTECTED_SUCCESS_KEYS = [
  "ok",
  "productId",
  "resourceClass",
  "provenance",
  "limitation",
  "purposeKind",
  "purpose",
  "requestId",
  "offeringId",
  "serviceId",
  "providerId",
  "evidence",
  "payload",
  "content",
] as const;
const MAX_ID_LENGTH = 256;
const MAX_CONTENT_LENGTH = 20_000;
const MAX_ITEM_TEXT_LENGTH = 2_000;
const MAX_ITEMS = 32;

function boundedString(value: unknown, max: number): value is string {
  return typeof value === "string" && value.length <= max && value.trim().length > 0;
}
function boundedStringArray(value: unknown, min: number): value is string[] {
  return (
    Array.isArray(value) &&
    value.length >= min &&
    value.length <= MAX_ITEMS &&
    value.every((item) => boundedString(item, MAX_ITEM_TEXT_LENGTH))
  );
}
function isPlainRecord(value: unknown): value is Record<string, unknown> {
  if (typeof value !== "object" || value === null || Array.isArray(value)) return false;
  const proto = Object.getPrototypeOf(value);
  return proto === Object.prototype || proto === null;
}

export function parseSocialMediaGuruProtectedSuccess(
  value: unknown,
): SocialMediaGuruProtectedSuccessResult | null {
  if (!isPlainRecord(value)) return null;
  const keys = Object.keys(value);
  if (keys.length !== PROTECTED_SUCCESS_KEYS.length) return null;
  if (!keys.every((key) => (PROTECTED_SUCCESS_KEYS as readonly string[]).includes(key)))
    return null;
  const r = value;
  if (r.ok !== true) return null;
  if (r.productId !== SOCIAL_MEDIA_GURU_PRODUCT_ID) return null;
  if (r.resourceClass !== SOCIAL_MEDIA_GURU_RESOURCE_CLASS) return null;
  if (r.provenance !== SOCIAL_MEDIA_GURU_PROVENANCE) return null;
  if (r.limitation !== SOCIAL_MEDIA_GURU_LIMITATION) return null;
  if (r.purposeKind !== SOCIAL_MEDIA_GURU_SUPPORTED_PURPOSE_KIND) return null;
  if (r.serviceId !== SOCIAL_MEDIA_GURU_SERVICE_ID) return null;
  if (r.providerId !== SOCIAL_MEDIA_GURU_PROVIDER_ID) return null;
  if (!boundedString(r.purpose, SOCIAL_MEDIA_GURU_PURPOSE_MAX_LENGTH)) return null;
  if (r.requestId !== null && !boundedString(r.requestId, MAX_ID_LENGTH)) return null;
  if (r.offeringId !== null && !boundedString(r.offeringId, MAX_ID_LENGTH)) return null;
  if (!boundedString(r.content, MAX_CONTENT_LENGTH)) return null;
  if (!Array.isArray(r.evidence) || r.evidence.length === 0 || r.evidence.length > MAX_ITEMS)
    return null;
  const evidence: SocialMediaGuruProtectedSuccessResult["evidence"] = [];
  for (const item of r.evidence) {
    if (!isPlainRecord(item) || Object.keys(item).length !== 3) return null;
    if (!boundedString(item.label, MAX_ID_LENGTH) || !boundedString(item.text, MAX_ITEM_TEXT_LENGTH))
      return null;
    if (typeof item.observedAt !== "number" || !Number.isFinite(item.observedAt)) return null;
    evidence.push({
      label: item.label,
      text: item.text,
      observedAt: item.observedAt,
    });
  }
  const payload = r.payload;
  if (!isPlainRecord(payload) || Object.keys(payload).length !== 8) return null;
  if (!boundedStringArray(payload.platforms, 1)) return null;
  if (!boundedStringArray(payload.audienceBehavior, 1)) return null;
  if (!boundedStringArray(payload.trendingFormats, 1)) return null;
  if (!boundedStringArray(payload.engagementTendencies, 1)) return null;
  if (!boundedStringArray(payload.messagingThemes, 1)) return null;
  if (!boundedStringArray(payload.channelDifferences, 1)) return null;
  if (!boundedStringArray(payload.demographicStyleAggregates, 1)) return null;
  if (!boundedStringArray(payload.contentRecommendations, 1)) return null;
  return {
    ok: true,
    productId: SOCIAL_MEDIA_GURU_PRODUCT_ID,
    resourceClass: SOCIAL_MEDIA_GURU_RESOURCE_CLASS,
    provenance: SOCIAL_MEDIA_GURU_PROVENANCE,
    limitation: SOCIAL_MEDIA_GURU_LIMITATION,
    purposeKind: SOCIAL_MEDIA_GURU_SUPPORTED_PURPOSE_KIND,
    purpose: r.purpose,
    requestId: r.requestId as string | null,
    offeringId: r.offeringId as string | null,
    serviceId: SOCIAL_MEDIA_GURU_SERVICE_ID,
    providerId: SOCIAL_MEDIA_GURU_PROVIDER_ID,
    evidence,
    payload: {
      platforms: [...payload.platforms],
      audienceBehavior: [...payload.audienceBehavior],
      trendingFormats: [...payload.trendingFormats],
      engagementTendencies: [...payload.engagementTendencies],
      messagingThemes: [...payload.messagingThemes],
      channelDifferences: [...payload.channelDifferences],
      demographicStyleAggregates: [...payload.demographicStyleAggregates],
      contentRecommendations: [...payload.contentRecommendations],
    },
    content: r.content,
  };
}

